<p>
	 Обновленная База отдыха «Салют» работает для вас круглый год! Она расположена на берегу Волги в одном из красивейших мест Самарской области у подножия Царева Кургана в месте слияния рек Волга, Сок и Курумка с видом на Жигулевские горы. <br>
	 Здесь созданы все необходимые условия для семейного, молодежного и корпоративного отдыха, проведения различных торжественных мероприятий, свадеб, юбилеев, спартакиад и т.д.
</p>
<p>
	 База отдыха «Салют» предлагает следующие варианты размещения:
</p>
<p>
</p>
<ul>
	<li> <b>Коттедж двухэтажный:</b> комфортабельный и просторный номер для 6 - 8 человек, отдельные беседки (с удобствами, в комплектацию входят набор посуды, СВЧ-печь, электрический чайник, телевизор, холодильник, кухня, ванная комната в номере);</li>
	<li> <b>Дом из кирпича с верандой:</b> комфортабельный и просторный коттедж для 6 - 9 человек, отдельная беседка (с удобствами, в комплектацию входят набор посуды, СВЧ-печь, электрический чайник, телевизор, холодильник, кухня, ванная комната в номере); </li>
	<li> <b>Дом из бруса с верандой:</b> комфортабельный и просторный номер для 2 - 4 человек (с удобствами, в комплектацию входят набор посуды, СВЧ-печь, электрический чайник, телевизор, холодильник, кухня, ванная комната в номере).</li>
</ul>
